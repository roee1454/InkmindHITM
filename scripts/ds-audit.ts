/**
 * Design-system audit: runs only the design-system lint rules (messages tagged `[ds:<pillar>]`,
 * see eslint/design-system/) over src/ and counts what is left, per area and pillar.
 *
 *   pnpm ds:audit                     table for the whole app
 *   pnpm ds:audit --area calendar     one area (features/<name>, shell, ui, routes, other)
 *   pnpm ds:audit --path src/routes/_app/calendar.tsx   files under a path prefix
 *   pnpm ds:audit --area calendar --list                every violation, file:line
 *   pnpm ds:audit --write             regenerate docs/im-design-system/audit.md
 *
 * Exits 1 when the selection has violations, so "done" for an area is a 0 exit.
 */
import { writeFileSync } from 'node:fs'
import path from 'node:path'
import { ESLint } from 'eslint'

const ROOT = path.resolve(import.meta.dirname, '..')
const PILLARS = ['colors', 'components', 'typography', 'icons'] as const
type Pillar = (typeof PILLARS)[number]
const TAG = /^\[ds:(colors|components|typography|icons)\]\s*/

interface Violation {
  file: string
  line: number
  area: string
  pillar: Pillar
  message: string
}

function argValue(flag: string): string | undefined {
  const i = process.argv.indexOf(flag)
  return i === -1 ? undefined : process.argv[i + 1]
}

/** features/<x> → x · components/ui → ui · components → shell · routes · everything else → other */
function areaOf(relFromSrc: string): string {
  const [top, second] = relFromSrc.split('/')
  if (top === 'features' && second) return second
  if (top === 'components') return second === 'ui' ? 'ui' : 'shell'
  if (top === 'routes') return 'routes'
  return 'other'
}

async function collect(): Promise<Violation[]> {
  const eslint = new ESLint({
    cwd: ROOT,
    ruleFilter: ({ ruleId }) => ruleId === 'no-restricted-syntax' || ruleId === 'no-restricted-imports',
  })
  const results = await eslint.lintFiles(['src/**/*.{ts,tsx}'])
  const out: Violation[] = []
  for (const result of results) {
    const file = path.relative(ROOT, result.filePath)
    for (const m of result.messages) {
      const tag = TAG.exec(m.message)
      if (!tag?.[1]) continue
      out.push({
        file,
        line: m.line,
        area: areaOf(path.relative(path.join(ROOT, 'src'), result.filePath)),
        pillar: tag[1] as Pillar,
        message: m.message.replace(TAG, ''),
      })
    }
  }
  return out
}

function table(violations: Violation[]): string {
  const areas = [...new Set(violations.map((v) => v.area))].sort()
  const count = (area: string | null, pillar: Pillar | null) =>
    violations.filter((v) => (area === null || v.area === area) && (pillar === null || v.pillar === pillar)).length
  const rows = areas
    .map((area) => ({ area, total: count(area, null), cells: PILLARS.map((p) => count(area, p)) }))
    .sort((a, b) => b.total - a.total)
  const lines = [
    `| area | ${PILLARS.join(' | ')} | total |`,
    `|---|${PILLARS.map(() => '---:').join('|')}|---:|`,
    ...rows.map((r) => `| ${r.area} | ${r.cells.join(' | ')} | **${r.total}** |`),
    `| **all** | ${PILLARS.map((p) => count(null, p)).join(' | ')} | **${violations.length}** |`,
  ]
  return lines.join('\n')
}

async function main() {
  const area = argValue('--area')
  const prefix = argValue('--path')
  const all = await collect()
  const selected = all.filter((v) => (!area || v.area === area) && (!prefix || v.file.startsWith(prefix)))

  console.log(selected.length ? table(selected) : 'No design-system violations in this selection.')
  if (process.argv.includes('--list')) {
    for (const v of [...selected].sort((a, b) => a.file.localeCompare(b.file) || a.line - b.line)) {
      console.log(`${v.file}:${v.line}  [${v.pillar}] ${v.message}`)
    }
  }
  if (process.argv.includes('--write')) {
    const doc = [
      '# Design-system audit',
      '',
      `Generated by \`pnpm ds:audit --write\` on ${new Date().toISOString().slice(0, 10)}. Counts the lint`,
      'rules in `eslint/design-system/` (messages tagged `[ds:<pillar>]`). An area is done at 0.',
      '',
      table(all),
      '',
    ].join('\n')
    writeFileSync(path.join(ROOT, 'docs/im-design-system/audit.md'), doc)
    console.log('\nWrote docs/im-design-system/audit.md')
  }
  process.exitCode = selected.length ? 1 : 0
}

await main()
