/**
 * The closed Inkmind icon registry: every icon the app may draw, by what it means.
 *
 * - Names are semantic kebab-case (`edit`, `send`, `close`), never the glyph's name.
 * - `weight` follows the fill rule: a glyph with an inside is `fill`; a pure stroke (check, close,
 *   plus, arrows, link, attach, more, menu, spinner…) is `bold`, because Phosphor's `fill` weight
 *   boxes a stroke into a solid square. Carets are solid `fill` triangles.
 * - `mirrorInRtl` flips a glyph that points somewhere. The app root is `dir="rtl"`, so these
 *   render mirrored; the call site never decides.
 *
 * This is the only file in the app that imports `@phosphor-icons/react` (eslint/design-system/icons.js).
 * Render with `<IMIcon name="…" />` from `./icon`. Rules and the full table: docs/design-system/icons.md.
 */
